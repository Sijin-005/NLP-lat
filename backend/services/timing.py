"""Measurement logic, kept separate from the HTTP layer.

The routers deal with requests and responses; this module holds the actual
timing work, so it can be reasoned about (and reused) without a web framework
in the way.

All timings use `time.perf_counter()`: it is monotonic and high-resolution,
which matters when the quantities involved are single-digit milliseconds.
`time.time()` is unsuitable here because it can step backwards when the system
clock is adjusted.
"""

from __future__ import annotations

import asyncio
import json
import time
from dataclasses import dataclass
from typing import AsyncIterator

# Roughly how many bytes of UTF-8 text one token corresponds to. Used only to
# give the echo endpoint a realistically sized body; it is not a claim about
# any particular tokenizer.
BYTES_PER_TOKEN = 4

# Words cycled through when streaming. Nothing is generated by a model — this
# is fixed text whose *arrival times* are what gets measured.
_STREAM_WORDS = (
    "Natural language processing covers many tasks and large language models "
    "are one modern approach within it. This text is streamed by the local "
    "backend so that arrival times can be measured with a real clock."
).split()


@dataclass(frozen=True)
class HandlerTiming:
    """How long a request handler spent, broken into the parts we can attribute."""

    receive_to_handler_ms: float
    processing_ms: float
    work_ms: float


def build_payload(payload_tokens: int) -> str:
    """Filler of a believable size for the requested notional token count."""
    return "x" * max(0, payload_tokens * BYTES_PER_TOKEN)


async def perform_server_work(work_ms: float) -> float:
    """Sleep for `work_ms` and report how long that actually took.

    Requested and actual durations differ — the event loop does not wake with
    microsecond precision — so we measure rather than echo the request back.
    """
    started = time.perf_counter()
    if work_ms > 0:
        await asyncio.sleep(work_ms / 1000)
    return (time.perf_counter() - started) * 1000


def measure_handler(
    handler_started: float, arrived_at: float, actual_work_ms: float
) -> HandlerTiming:
    """Summarise a handler's timing at the moment it is about to respond."""
    return HandlerTiming(
        receive_to_handler_ms=round((handler_started - arrived_at) * 1000, 3),
        processing_ms=round((time.perf_counter() - handler_started) * 1000, 3),
        work_ms=round(actual_work_ms, 3),
    )


async def stream_chunks(
    chunks: int, chunk_delay_ms: float, first_chunk_delay_ms: float
) -> AsyncIterator[str]:
    """Yield newline-delimited JSON chunks with scripted delays.

    The delays are set by the caller, so the *server* side is scripted; what the
    browser measures on the other end — when each chunk genuinely arrived over a
    real HTTP connection — is a real measurement. That contrast is the point of
    the exercise, and the UI labels it accordingly.

    `first_chunk_delay_ms` stands in for the queue and prefill a real provider
    would do before its first token.
    """
    started = time.perf_counter()

    if first_chunk_delay_ms > 0:
        await asyncio.sleep(first_chunk_delay_ms / 1000)

    for index in range(chunks):
        if index > 0 and chunk_delay_ms > 0:
            await asyncio.sleep(chunk_delay_ms / 1000)

        yield json.dumps(
            {
                "index": index,
                "text": _STREAM_WORDS[index % len(_STREAM_WORDS)] + " ",
                "server_elapsed_ms": round((time.perf_counter() - started) * 1000, 3),
            }
        ) + "\n"

    yield json.dumps(
        {
            "index": -1,
            "done": True,
            "server_total_ms": round((time.perf_counter() - started) * 1000, 3),
        }
    ) + "\n"
